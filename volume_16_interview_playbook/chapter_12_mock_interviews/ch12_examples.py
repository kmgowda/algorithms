from __future__ import annotations

import itertools
import string
from collections import deque
from functools import lru_cache


# ---- Mock 1: 3Sum (LeetCode 15) ------------------------------------------------------------------------
def three_sum_brute(nums: list[int]) -> list[tuple[int, int, int]]:
    """Brute force: every triple, O(n^3); a set removes duplicate triples."""
    return sorted({tuple(sorted(t)) for t in itertools.combinations(nums, 3) if sum(t) == 0})


def three_sum(nums: list[int]) -> list[tuple[int, int, int]]:
    """Sort, fix the first number, then two pointers for the other two; skip equal values to avoid duplicates. O(n^2)."""
    nums = sorted(nums)
    out = []
    for i in range(len(nums) - 2):
        if i and nums[i] == nums[i - 1]:
            continue
        lo, hi = i + 1, len(nums) - 1
        while lo < hi:
            s = nums[i] + nums[lo] + nums[hi]
            if s < 0:
                lo += 1
            elif s > 0:
                hi -= 1
            else:
                out.append((nums[i], nums[lo], nums[hi]))
                lo += 1
                while lo < hi and nums[lo] == nums[lo - 1]:
                    lo += 1
    return out


# ---- Mock 2: Word Ladder (LeetCode 127) ----------------------------------------------------------------
def ladder_length(begin: str, end: str, words: list[str]) -> int:
    """Fewest words from begin to end changing one letter at a time, each step a dictionary word.
    'Fewest steps' in an unweighted graph -> BFS. Neighbours are generated by trying 26 letters per position,
    O(L x 26) per word instead of comparing against every dictionary word."""
    dictionary = set(words)
    if end not in dictionary:
        return 0
    q, seen = deque([(begin, 1)]), {begin}
    while q:
        word, steps = q.popleft()
        if word == end:
            return steps
        for i in range(len(word)):
            for ch in string.ascii_lowercase:
                nxt = word[:i] + ch + word[i + 1:]
                if nxt in dictionary and nxt not in seen:
                    seen.add(nxt)
                    q.append((nxt, steps + 1))
    return 0


# ---- Mock 3: Word Break (LeetCode 139) -----------------------------------------------------------------
def word_break_brute(s: str, words: list[str]) -> bool:
    """Brute force: try every first word, recurse on the rest - exponential on inputs like 'aaaa...b'."""
    if not s:
        return True
    return any(s.startswith(w) and word_break_brute(s[len(w):], words) for w in words if w)


def word_break(s: str, words: list[str]) -> bool:
    """DP: ok[i] = some dictionary word ends at i and ok[start of that word]. O(n x longest word)."""
    vocab, longest = set(words), max(map(len, words), default=0)
    ok = [True] + [False] * len(s)
    for i in range(1, len(s) + 1):
        ok[i] = any(ok[j] and s[j:i] in vocab for j in range(max(0, i - longest), i))
    return ok[-1]


def count_calls(s: str, words: list[str]) -> tuple[int, int]:
    """How many recursive calls the brute force makes vs memoized calls - the evidence for switching to DP."""
    calls = 0

    def brute(rest: str) -> bool:
        nonlocal calls
        calls += 1
        return not rest or any(rest.startswith(w) and brute(rest[len(w):]) for w in words)

    brute(s)
    plain, calls = calls, 0

    @lru_cache(maxsize=None)
    def memo(rest: str) -> bool:
        nonlocal calls
        calls += 1
        return not rest or any(rest.startswith(w) and memo(rest[len(w):]) for w in words)

    memo(s)
    return plain, calls


if __name__ == "__main__":
    print(three_sum([-1, 0, 1, 2, -1, -4]), three_sum_brute([-1, 0, 1, 2, -1, -4]))
    print(ladder_length("hit", "cog", ["hot", "dot", "dog", "lot", "log", "cog"]))
    print(word_break("leetcode", ["leet", "code"]), word_break("catsandog", ["cats", "dog", "sand", "and", "cat"]))
    print(count_calls("a" * 18 + "b", ["a", "aa", "aaa"]))
